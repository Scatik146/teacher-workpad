: ВДВОЕ ( цифра -- цифра' ) 2* DUP 9 > IF 9 - THEN ;
: ЦИФРА ( n -- n' цифра ) 10 /MOD SWAP ;
: ПАРА ( сумма n -- сумма' n' ) ЦИФРА ROT + SWAP ЦИФРА ВДВОЕ ROT + SWAP ;
: СУММА-ЛУНА ( n -- сумма ) 0 SWAP BEGIN DUP WHILE ПАРА REPEAT DROP ;
