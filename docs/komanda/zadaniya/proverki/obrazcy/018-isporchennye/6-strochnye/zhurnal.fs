\ Журнал входов: число блокировок. Коды: 0 — вход, 1 — пароль, 2 — код из SMS, 3 — вопрос.
\ ПОРОГИ: порог блокировки по коду события (ячейка 0 — удачный вход, не нужна)
CREATE ПОРОГИ 0 , 3 , 3 , 2 ,
\ СЧЕТА: ошибки подряд по коду события
CREATE СЧЕТА 0 , 0 , 0 , 0 ,
\ БЛОКОВ: число блокировок
VARIABLE БЛОКОВ
\ СЧЁТ: адрес счёта события
: СЧЁТ ( код -- адрес ) CELLS СЧЕТА + ;
\ ПОРОГ: порог события
: ПОРОГ ( код -- порог ) CELLS ПОРОГИ + @ ;
\ ОБНУЛИТЬ: все счета — в ноль
: ОБНУЛИТЬ ( -- ) СЧЕТА 4 CELLS ERASE ;
\ ДОШЛО?: счёт события дошёл до порога
: ДОШЛО? ( код -- флаг ) DUP СЧЁТ @ swap ПОРОГ = ;
\ БЛОКИРОВАТЬ: ещё одна блокировка, счёт события — заново
: БЛОКИРОВАТЬ ( код -- ) 0 SWAP СЧЁТ ! 1 БЛОКОВ +! ;
\ ОШИБКА: счёт события +1, на пороге — блокировка
: ОШИБКА ( код -- ) 1 OVER СЧЁТ +! DUP ДОШЛО? IF БЛОКИРОВАТЬ ELSE DROP THEN ;
\ СОБЫТИЕ: удачный вход обнуляет счета, ошибка считается
: СОБЫТИЕ ( код -- ) ?DUP IF ОШИБКА ELSE ОБНУЛИТЬ THEN ;
\ НАЧАТЬ: счета и блокировки — с нуля
: НАЧАТЬ ( -- ) ОБНУЛИТЬ 0 БЛОКОВ ! ;
\ БЛОКИРОВКИ: число блокировок для журнала из длина ячеек
: БЛОКИРОВКИ ( адрес длина -- число ) НАЧАТЬ CELLS OVER + SWAP ?DO I @ СОБЫТИЕ 1 CELLS +LOOP БЛОКОВ @ ;
